        CountId    INT           IDENTITY(1,1) NOT NULL PRIMARY KEY,
        BranchCode INT           NOT NULL,
        CountName  NVARCHAR(200) NOT NULL,
        CreatedAt  DATETIME2     NOT NULL DEFAULT SYSDATETIME(),
