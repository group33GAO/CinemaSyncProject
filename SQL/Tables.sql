-- ---------------------------------------------------------
-- Branches
-- ---------------------------------------------------------
IF NOT EXISTS (SELECT 1 FROM sys.tables WHERE name = 'Branches')
BEGIN
    CREATE TABLE Branches
    (
        BranchCode   INT          NOT NULL PRIMARY KEY,
        BranchName   NVARCHAR(100) NOT NULL,
        City         NVARCHAR(100) NOT NULL,
        MapiSiteId   INT          NULL
    );
END;
GO

-- ---------------------------------------------------------
-- Users
-- ---------------------------------------------------------
IF NOT EXISTS (SELECT 1 FROM sys.tables WHERE name = 'Users')
BEGIN
    CREATE TABLE Users
    (
        UserId       INT           IDENTITY(1,1) NOT NULL PRIMARY KEY,
        Email        NVARCHAR(150) NOT NULL UNIQUE,
        PasswordHash NVARCHAR(256) NOT NULL,
        FullName     NVARCHAR(150) NOT NULL,
        Role         NVARCHAR(30)  NOT NULL,
        BranchCode   INT           NULL,
        LastLogin    DATETIME2     NULL,
        CONSTRAINT FK_Users_Branches FOREIGN KEY (BranchCode)
            REFERENCES Branches(BranchCode)
    );
END;
GO

-- ---------------------------------------------------------
-- Products (shared catalog, seeded from HotCinema inventory)
-- ---------------------------------------------------------
IF NOT EXISTS (SELECT 1 FROM sys.tables WHERE name = 'Products')
BEGIN
    CREATE TABLE Products
    (
        ProductId             INT           IDENTITY(1,1) NOT NULL PRIMARY KEY,
        Barcode               NVARCHAR(50)  NULL,
        ProductName           NVARCHAR(200) NOT NULL,
        UnitsPerPackage       INT           NOT NULL,
        Supplier              NVARCHAR(100) NOT NULL,
        SupplierMinOrder      NVARCHAR(300) NULL,
        DefaultRequiredStock  INT           NULL,
        Notes                 NVARCHAR(500) NULL,
        IsActive              BIT           NOT NULL DEFAULT 1
    );
END;
GO

-- ---------------------------------------------------------
-- BranchInventory (per-branch current stock + optional override required)
-- ---------------------------------------------------------
IF NOT EXISTS (SELECT 1 FROM sys.tables WHERE name = 'BranchInventory')
BEGIN
    CREATE TABLE BranchInventory
    (
        BranchCode    INT       NOT NULL,
        ProductId     INT       NOT NULL,
        CurrentStock  INT       NOT NULL DEFAULT 0,
        RequiredStock INT       NULL,
        LastUpdated   DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
        CONSTRAINT PK_BranchInventory PRIMARY KEY (BranchCode, ProductId),
        CONSTRAINT FK_BranchInventory_Branches FOREIGN KEY (BranchCode)
            REFERENCES Branches(BranchCode),
        CONSTRAINT FK_BranchInventory_Products FOREIGN KEY (ProductId)
            REFERENCES Products(ProductId)
    );
END;
GO

